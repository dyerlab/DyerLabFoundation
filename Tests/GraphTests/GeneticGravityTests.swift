private let tolerance = 1e-10

// MARK: - Fixture decoding

/// A gamma written by R as a number, or as the string "Inf".
private struct FGamma: Decodable {
    let value: Double
    init(from decoder: Decoder) throws {
        let container = try decoder.singleValueContainer()
        if let number = try? container.decode(Double.self) {
            value = number
        } else {
            let text = try container.decode(String.self)
            guard text == "Inf" else {
                throw DecodingError.dataCorruptedError(in: container, debugDescription: "gamma \(text)")
            }
            value = .infinity
        }
    }
}
private struct FEdge: Decodable { let from: String; let to: String; let weight: Double }
private struct FGravityEdge: Decodable {
    let from: String; let to: String; let weight: Double
    let w_from: Double; let w_to: Double; let Delta: Double; let Delta0: Double
}
private struct FScoreRow: Decodable {
    let Stratum: String; let S: Double; let gravity: Double; let balance: Double
    let degree: Int; let component: Int; let S0: Double?; let n: Double?
}
private struct FDecomposition: Decodable { let sum_delta: Double; let reproduced: Double; let residual: Double }
private struct FScores: Decodable {
    let rows: [FScoreRow]
    let degree_share: Double?; let cor_S_S0: Double?; let cor_S_degree: Double?; let gradient_share: Double?
    let dbar_decomposition: FDecomposition?
}
private struct FGammaCase: Decodable {
    let gamma: FGamma
    let W: [[Double?]]
    let edges: [FGravityEdge]
    let scores: FScores
    let pgd: [[Double?]]?
}
private struct FCase: Decodable {
    let nodes: [String]
    let edges: [FEdge]
    let x: [String: Double]?
    let cases: [FGammaCase]
}

private func loadFixtures() throws -> [String: FCase] {
    let url = URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent()
        .appendingPathComponent("Fixtures/gravity_fixtures.json")
    return try JSONDecoder().decode([String: FCase].self, from: Data(contentsOf: url))
}

private func buildGraph(_ fixture: FCase) -> Graph {
    let nodes = fixture.nodes.map { Node(name: $0, size: 1.0) }
    let byName = Dictionary(uniqueKeysWithValues: nodes.map { ($0.name, $0) })
    let edges = fixture.edges.map { Edge(fromNode: byName[$0.from]!, toNode: byName[$0.to]!, weight: $0.weight) }
    return Graph(nodes: nodes, edges: edges)
}

/// `nil` in a fixture is R's NA / Inf: matches any non-finite value.
private func matches(_ actual: Double, _ expected: Double?, tolerance: Double = tolerance) -> Bool {
    guard let expected else { return !actual.isFinite }
    return abs(actual - expected) < tolerance
}

private let caseNames = ["chain", "chain_x", "tree", "disjoint", "gravity"]

// MARK: - R parity

@Test(arguments: caseNames)
func neighbourhoodWeightsMatchR(_ name: String) throws {
    let fixture = try #require(loadFixtures()[name])
    let graph = buildGraph(fixture)
    for gammaCase in fixture.cases {
        let gamma = gammaCase.gamma.value
        let W = try #require(NeighbourhoodWeights(graph: graph, gamma: gamma))
        #expect(W.rowNames == fixture.nodes && W.colNames == fixture.nodes)
        for i in 0..<W.rows {
            for j in 0..<W.cols {
                #expect(matches(W[i, j], gammaCase.W[i][j]),
                        "\(name) γ=\(gamma) W[\(i),\(j)]: \(W[i, j]) vs \(String(describing: gammaCase.W[i][j]))")
            }
        }
    }
}

@Test(arguments: caseNames)
func gravityEdgesMatchR(_ name: String) throws {
    let fixture = try #require(loadFixtures()[name])
    let graph = buildGraph(fixture)
    for gammaCase in fixture.cases {
        let gamma = gammaCase.gamma.value
        let edges = try #require(GravityEdges(graph: graph, gamma: gamma, x: fixture.x))
        #expect(edges.count == gammaCase.edges.count)
        for (edge, expected) in zip(edges, gammaCase.edges) {
            let label = "\(name) γ=\(gamma) \(expected.from)-\(expected.to)"
            #expect(edge.from == expected.from && edge.to == expected.to, "\(label): orientation")
            #expect(edge.weight == expected.weight, "\(label) weight")
            #expect(matches(edge.wFrom, expected.w_from), "\(label) w_from")
            #expect(matches(edge.wTo, expected.w_to), "\(label) w_to")
            #expect(matches(edge.delta, expected.Delta), "\(label) Delta: \(edge.delta) vs \(expected.Delta)")
            #expect(matches(edge.delta0, expected.Delta0), "\(label) Delta0")
        }
    }
}

@Test(arguments: caseNames)
func sourceSinkScoresMatchR(_ name: String) throws {
    let fixture = try #require(loadFixtures()[name])
    let graph = buildGraph(fixture)
    for gammaCase in fixture.cases {
        let gamma = gammaCase.gamma.value
        let result = try #require(SourceSinkScores(graph: graph, gamma: gamma, x: fixture.x))
        let expected = gammaCase.scores
        #expect(result.scores.count == expected.rows.count)
        for (row, exp) in zip(result.scores, expected.rows) {
            let label = "\(name) γ=\(gamma) \(exp.Stratum)"
            #expect(row.stratum == exp.Stratum)
            #expect(matches(row.s, exp.S), "\(label) S: \(row.s) vs \(exp.S)")
            #expect(matches(row.gravity, exp.gravity), "\(label) gravity")
            #expect(matches(row.balance, exp.balance), "\(label) balance")
            #expect(row.degree == exp.degree, "\(label) degree")
            #expect(row.component == exp.component, "\(label) component")
            #expect(matches(row.s0, exp.S0), "\(label) S0: \(row.s0) vs \(String(describing: exp.S0))")
            if let n = exp.n { #expect(row.n.map { abs($0 - n) < tolerance } ?? false, "\(label) n") }
            else { #expect(row.n == nil, "\(label) n should be nil without x") }
        }
        #expect(matches(result.degreeShare, expected.degree_share), "\(name) γ=\(gamma) degree_share")
        #expect(matches(result.corSS0, expected.cor_S_S0), "\(name) γ=\(gamma) cor_S_S0")
        #expect(matches(result.corSDegree, expected.cor_S_degree), "\(name) γ=\(gamma) cor_S_degree")
        #expect(matches(result.gradientShare, expected.gradient_share), "\(name) γ=\(gamma) gradient_share")
        #expect(result.gamma == gamma)

        if let exp = expected.dbar_decomposition {
            let dec = try #require(result.deltaBarDecomposition, "\(name): missing dbar decomposition")
            #expect(matches(dec.sumDelta, exp.sum_delta) && matches(dec.reproduced, exp.reproduced)
                    && matches(dec.residual, exp.residual), "\(name) γ=\(gamma) dbar_decomposition")
        } else {
            #expect(result.deltaBarDecomposition == nil)
        }
    }
}

@Test(arguments: caseNames)
func partitionedGeneticDistanceMatchesR(_ name: String) throws {
    let fixture = try #require(loadFixtures()[name])
    let graph = buildGraph(fixture)
    for gammaCase in fixture.cases {
        guard let expected = gammaCase.pgd else { continue }
        let gamma = gammaCase.gamma.value
        let D = try #require(PartitionedGeneticDistance(graph: graph, gamma: gamma))
        #expect(D.rowNames == fixture.nodes)
        for i in 0..<D.rows {
            for j in 0..<D.cols {
                #expect(matches(D[i, j], expected[i][j]),
                        "\(name) γ=\(gamma) pGD[\(i),\(j)]: \(D[i, j]) vs \(String(describing: expected[i][j]))")
            }
        }
    }
}

// MARK: - Properties (gstudio's test-gravity.R)

@Test func gravityDeltaIsNegatedGraphAsymmetriesDelta() throws {
    let graph = buildGraph(try #require(loadFixtures()["chain"]))
    let edges = try #require(GravityEdges(graph: graph, gamma: 0.5))
    let asym = try #require(GraphAsymmetries(graph: graph, scale: 0.5))
    for (gravity, directional) in zip(edges, asym.edges) {
        #expect(abs(gravity.delta + directional.delta) < 1e-12)
    }
}

@Test func sourceSinkScoresReproduceDeltaOnATree() throws {
    let graph = buildGraph(try #require(loadFixtures()["tree"]))
    let result = try #require(SourceSinkScores(graph: graph))
    #expect(abs(result.gradientShare - 1) < 1e-10)
    let S = Dictionary(uniqueKeysWithValues: result.scores.map { ($0.stratum, $0.s) })
    for edge in try #require(GravityEdges(graph: graph)) {
        #expect(abs(edge.delta - (S[edge.from]! - S[edge.to]!)) < 1e-10)
    }
}

@Test func gravityBalancesAndScoresCentre() throws {
    let graph = buildGraph(try #require(loadFixtures()["chain"]))
    for gamma in [0.5, 1.0, .infinity] {
        let result = try #require(SourceSinkScores(graph: graph, gamma: gamma))
        #expect(result.scores.allSatisfy { abs($0.balance - ($0.gravity - 1)) < 1e-12 })
        #expect(abs(result.scores.reduce(0) { $0 + $1.balance }) < 1e-10)
        #expect(abs(result.scores.reduce(0) { $0 + $1.s }) < 1e-10)
    }
    // Flat kernel is pure degree.
    let flat = try #require(SourceSinkScores(graph: graph, gamma: .infinity))
    #expect(abs(flat.degreeShare - 1) < 1e-12)
    #expect(abs(flat.corSS0 - 1) < 1e-10)
}

@Test func rescalingEdgeWeightsLeavesGravityUnchanged() throws {
    let fixture = try #require(loadFixtures()["chain"])
    let graph = buildGraph(fixture)
    let scaled = buildGraph(FCaseScaled(fixture, by: 7.3))
    let a = try #require(SourceSinkScores(graph: graph)), b = try #require(SourceSinkScores(graph: scaled))
    #expect(zip(a.scores, b.scores).allSatisfy { abs($0.s - $1.s) < 1e-12 })
}

@Test func partitionedArcsSumToEdgeWeight() throws {
    let graph = buildGraph(try #require(loadFixtures()["chain"]))
    let directed = try #require(PartitionedGeneticDistanceGraph(graph: graph))
    #expect(directed.nodes.map { $0.name } == graph.nodes.map { $0.name })
    let names = directed.nodeNameByID()
    var arc: [String: Double] = [:]
    for edge in directed.edges { arc["\(names[edge.fromNode]!)>\(names[edge.toNode]!)"] = edge.weight }
    let undirected = graph.undirectedEdgeList()
    #expect(directed.edges.count == 2 * undirected.count)
    for edge in undirected {
        let total = arc["\(edge.from)>\(edge.to)"]! + arc["\(edge.to)>\(edge.from)"]!
        #expect(abs(total - edge.weight) < 1e-12)
    }
}

@Test func gravityRejectsInvalidInput() throws {
    let fixture = try #require(loadFixtures()["chain"])
    let graph = buildGraph(fixture)
    #expect(NeighbourhoodWeights(graph: graph, gamma: 0) == nil)
    #expect(NeighbourhoodWeights(graph: graph, gamma: -1) == nil)
    #expect(SourceSinkScores(graph: graph, gamma: .nan) == nil)
    #expect(GravityEdges(graph: graph, x: ["P1": 1]) == nil)            // x missing nodes
    #expect(PartitionedGeneticDistance(graph: graph, gamma: 0) == nil)
}

/// The fixture with every edge weight multiplied by `factor`.
private func FCaseScaled(_ fixture: FCase, by factor: Double) -> FCase {
    FCase(nodes: fixture.nodes,
          edges: fixture.edges.map { FEdge(from: $0.from, to: $0.to, weight: $0.weight * factor) },
          x: fixture.x, cases: [])
}
