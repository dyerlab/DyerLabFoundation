// MARK: - Fixture decoding

private struct RSEdge: Decodable { let from: String; let to: String }
private struct RSRandomize: Decodable {
    let seed: Int; let mode: String
    let node_names: [String]
    let edges: [RSEdge]
    let node_count: Int; let edge_count: Int
}
private struct RSBandwidthRow: Decodable {
    let from: String; let to: String
    let delta: Double; let statistic: Double; let p_value: Double
}
private struct RSBandwidth: Decodable { let seed: Int; let nperm: Int; let rows: [RSBandwidthRow] }
private struct RSNetwork: Decodable {
    let seed: Int; let nperm: Int; let rewire: String
    let statistic: Double; let p_value: Double
    let null: [Double]
}
private struct RSWeightedEdge: Decodable { let from: String; let to: String; let weight: Double? }
private struct RSDataset: Decodable {
    let nodes: [String]?
    let node_names: [String]?
    let edges: [RSWeightedEdge]
    let randomize_full: RSRandomize
    let asymmetry_bandwidth: RSBandwidth?
    let asymmetry_network: RSNetwork?
}

private func loadResampling() throws -> [String: RSDataset] {
    let url = URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent()
        .appendingPathComponent("Fixtures/downstream_resampling.json")
    return try JSONDecoder().decode([String: RSDataset].self, from: Data(contentsOf: url))
}

private func buildGraph(_ dataset: RSDataset) -> Graph {
    let names = dataset.nodes ?? dataset.node_names ?? []
    let nodes = names.map { Node(name: $0, size: 1.0) }
    let byName = Dictionary(uniqueKeysWithValues: nodes.map { ($0.name, $0) })
    let edges = dataset.edges.map { Edge(fromNode: byName[$0.from]!, toNode: byName[$0.to]!, weight: $0.weight ?? 1.0) }
    return Graph(nodes: nodes, edges: edges)
}

private func directedPairs(_ graph: Graph) -> [(String, String)] {
    let names = Dictionary(uniqueKeysWithValues: graph.nodes.map { ($0.id, $0.name) })
    return graph.edges.map { (names[$0.fromNode]!, names[$0.toNode]!) }
}

// MARK: - randomize_graph

private func degreeSequence(_ graph: Graph) -> [String: Int] {
    Dictionary(uniqueKeysWithValues: graph.nodes.map { ($0.name, graph.undirectedDegree(of: $0.name)) })
}

@Test(arguments: ["arapat", "cornus", "small"])
func randomizeDegreePreservesDegreesAndSimplicity(_ name: String) throws {
    let dataset = try #require(loadResampling()[name])
    let graph = buildGraph(dataset)
    let original = Set(directedPairs(graph).map { Set([$0.0, $0.1]) })

    for seed in [11, 909, 2026] {
        let result = try #require(RandomizeGraph(graph: graph, mode: .degree, seed: seed))

        // Same vertex set and order, same edge count, same degree for every node.
        #expect(result.nodes.map { $0.name } == graph.nodes.map { $0.name }, "\(name): vertex order")
        #expect(result.edges.count == graph.edges.count, "\(name): edge count")
        #expect(degreeSequence(result) == degreeSequence(graph), "\(name) seed \(seed): degree sequence")

        // Simple graph: no self-loops, no multi-edges.
        let pairs = directedPairs(result)
        #expect(pairs.allSatisfy { $0.0 != $0.1 }, "\(name): self-loop")
        let unordered = pairs.map { Set([$0.0, $0.1]) }
        #expect(Set(unordered).count == unordered.count, "\(name): multi-edge")

        // Swaps actually happened — unless the graph is complete (cornus is
        // K5), where no degree-preserving swap exists; R's rewire() leaves K5
        // unchanged too.
        let n = graph.nodes.count
        if original.count < n * (n - 1) / 2 {
            #expect(Set(unordered) != original, "\(name) seed \(seed): graph unchanged")
        } else {
            #expect(Set(unordered) == original, "\(name): complete graph cannot be rewired")
        }
    }

    // Deterministic for a given seed.
    let a = try #require(RandomizeGraph(graph: graph, mode: .degree, seed: 5))
    let b = try #require(RandomizeGraph(graph: graph, mode: .degree, seed: 5))
    #expect(directedPairs(a).map { "\($0.0)-\($0.1)" } == directedPairs(b).map { "\($0.0)-\($0.1)" })
}

/// The edge-swap chain samples uniformly over simple graphs with the given
/// degree sequence (in the limit). On the small 6-node fixture, check that every
/// node's neighbour frequencies over many rewires are close to the
/// configuration-model expectation's symmetry: each pair that can be connected
/// gets connected in some draws (the chain is not stuck near the start).
@Test func randomizeDegreeMixesOverReachableGraphs() throws {
    let dataset = try #require(loadResampling()["small"])
    let graph = buildGraph(dataset)
    var seen = Set<String>()
    for seed in 1...400 {
        let result = try #require(RandomizeGraph(graph: graph, mode: .degree, seed: seed))
        seen.insert(directedPairs(result).map { [$0.0, $0.1].sorted().joined(separator: "-") }.sorted().joined(separator: ","))
    }
    #expect(seen.count > 5, "only \(seen.count) distinct rewired graphs in 400 draws")
}

@Test(arguments: ["arapat", "cornus", "small"])
func randomizeFullMatchesRExactly(_ name: String) throws {
    let dataset = try #require(loadResampling()[name])
    let fixture = dataset.randomize_full
    let graph = buildGraph(dataset)
    let result = try #require(RandomizeGraph(graph: graph, mode: .full, seed: fixture.seed))

    #expect(result.nodes.count == fixture.node_count)
    #expect(result.edges.count == fixture.edge_count)

    // .full drops names in R (vertices become "1".."K" = position); our port
    // keeps the original vertex order, so map R's positional names to ours.
    let ourNames = graph.nodes.map { $0.name }
    func resolve(_ rName: String) -> String { Int(rName).map { ourNames[$0 - 1] } ?? rName }
    let expected = Set(fixture.edges.map { pair -> Set<String> in [resolve(pair.from), resolve(pair.to)] })
    let actual = Set(directedPairs(result).map { Set([$0.0, $0.1]) })
    #expect(actual == expected, "\(name): full-mode edge set")
}

// MARK: - asymmetry_bandwidth

@Test(arguments: ["arapat", "cornus"])
func asymmetryBandwidthMatchesRExactly(_ name: String) throws {
    let dataset = try #require(loadResampling()[name])
    let fixture = try #require(dataset.asymmetry_bandwidth)

    let result = try #require(AsymmetryBandwidthTest(graph: buildGraph(dataset),
                                                     permutations: fixture.nperm,
                                                     seed: fixture.seed))
    #expect(result.count == fixture.rows.count)

    var expectedByPair: [String: RSBandwidthRow] = [:]
    for row in fixture.rows { expectedByPair[key(row.from, row.to)] = row }

    for row in result {
        let exp = try #require(expectedByPair[key(row.from, row.to)])
        let orient = exp.from == row.from ? 1.0 : -1.0
        #expect(abs(row.delta - orient * exp.delta) < 1e-9, "\(name) \(row.from)-\(row.to) delta")
        // p-value is an exact k/(B+1) rational — must match to the ULP if the
        // RNG stream is identical.
        #expect(abs(row.pValue - exp.p_value) < 1e-12,
                "\(name) \(row.from)-\(row.to) p: \(row.pValue) vs \(exp.p_value)")
    }
}

// MARK: - asymmetry_network

/// The observed statistic is deterministic and must match R exactly; the null
/// comes from a functionally (not draw-for-draw) equivalent rewiring chain, so
/// it is compared to R's null distribution statistically.
@Test(arguments: ["arapat", "cornus"])
func asymmetryNetworkAgreesWithR(_ name: String) throws {
    let dataset = try #require(loadResampling()[name])
    let fixture = try #require(dataset.asymmetry_network)

    let swiftPermutations = 999
    let result = try #require(AsymmetryNetworkTest(graph: buildGraph(dataset),
                                                   permutations: swiftPermutations,
                                                   rewire: .degree,
                                                   returnNull: true,
                                                   seed: fixture.seed))
    #expect(abs(result.statistic - fixture.statistic) < 1e-9, "\(name): observed mean|delta|")
    #expect(result.validPermutations == swiftPermutations)
    #expect(result.edgeCount == dataset.edges.count)

    // Null means agree within 4 standard errors.
    let swiftNull = try #require(result.nullDistribution)
    func meanVar(_ x: [Double]) -> (Double, Double) {
        let m = x.reduce(0, +) / Double(x.count)
        return (m, x.reduce(0) { $0 + ($1 - m) * ($1 - m) } / Double(x.count - 1))
    }
    let (rMean, rVar) = meanVar(fixture.null)
    let (sMean, sVar) = meanVar(swiftNull)
    let se = (rVar / Double(fixture.null.count) + sVar / Double(swiftNull.count)).squareRoot()
    #expect(abs(sMean - rMean) < 4 * se, "\(name): null mean \(sMean) vs R \(rMean) (se \(se))")
    #expect(abs(result.nullMean - sMean) < 1e-12)

    // Null spreads agree to within 25%.
    #expect(abs(sVar.squareRoot() / rVar.squareRoot() - 1) < 0.25,
            "\(name): null sd \(sVar.squareRoot()) vs R \(rVar.squareRoot())")

    // p-values agree within Monte-Carlo error of R's 200-draw estimate.
    let pTolerance = 4 * (fixture.p_value * (1 - fixture.p_value) / Double(fixture.nperm)).squareRoot()
        + 2.0 / Double(fixture.nperm)
    #expect(abs(result.pValue - fixture.p_value) < pTolerance,
            "\(name): p-value \(result.pValue) vs R \(fixture.p_value)")
}

// MARK: - AsymmetrySignificance dispatcher

@Test func asymmetrySignificanceDispatchesToBaseFunctions() throws {
    let dataset = try #require(loadResampling()["cornus"])
    let graph = buildGraph(dataset)

    let mechanism = try #require(AsymmetrySignificance(graph: graph, mode: .mechanism,
                                                       permutations: 200, pendants: .keep, seed: 4041))
    let bwBase = try #require(AsymmetryBandwidthTest(graph: graph, permutations: 200, seed: 4041))
    guard case .edges(let rows, let pendantCount) = mechanism else {
        Issue.record("expected edge rows for .mechanism"); return
    }
    #expect(pendantCount == nil)
    #expect(rows == bwBase)

    let existence = try #require(AsymmetrySignificance(graph: graph, mode: .existence,
                                                       permutations: 200, seed: 5051))
    let netBase = try #require(AsymmetryNetworkTest(graph: graph, permutations: 200, seed: 5051))
    guard case .existence(let net) = existence else {
        Issue.record("expected a graph-level test for .existence"); return
    }
    #expect(net == netBase)
}

@Test func asymmetrySignificancePendantHandling() throws {
    // Triangle A-B-C plus a pendant D hanging off A (degree(D) == 1).
    let names = ["A", "B", "C", "D"]
    let nodes = names.map { Node(name: $0, size: 1.0) }
    let n = Dictionary(uniqueKeysWithValues: nodes.map { ($0.name, $0) })
    let graph = Graph(nodes: nodes, edges: [
        Edge(fromNode: n["A"]!, toNode: n["B"]!, weight: 2),
        Edge(fromNode: n["A"]!, toNode: n["C"]!, weight: 3),
        Edge(fromNode: n["B"]!, toNode: n["C"]!, weight: 1),
        Edge(fromNode: n["A"]!, toNode: n["D"]!, weight: 2),
    ])

    guard case .edges(let kept, let keptCount) = try #require(
        AsymmetrySignificance(graph: graph, mode: .mechanism, permutations: 49, pendants: .warn, seed: 1)
    ) else { Issue.record("expected edge rows"); return }
    #expect(kept.count == 4)
    #expect(keptCount == 1)          // the A-D edge

    guard case .edges(let dropped, let droppedCount) = try #require(
        AsymmetrySignificance(graph: graph, mode: .mechanism, permutations: 49, pendants: .drop, seed: 1)
    ) else { Issue.record("expected edge rows"); return }
    #expect(dropped.count == 3)
    #expect(dropped.allSatisfy { $0.from != "D" && $0.to != "D" })
    #expect(droppedCount == 1)
}

@Test func asymmetryBandwidthReturnsNullOnRequest() throws {
    let dataset = try #require(loadResampling()["cornus"])
    let graph = buildGraph(dataset)
    let rows = try #require(AsymmetryBandwidthTest(graph: graph, permutations: 50, returnNull: true, seed: 3))
    #expect(rows.allSatisfy { $0.nullDistribution?.count == 50 })
    let plain = try #require(AsymmetryBandwidthTest(graph: graph, permutations: 50, seed: 3))
    #expect(plain.allSatisfy { $0.nullDistribution == nil })
    #expect(zip(rows, plain).allSatisfy { $0.pValue == $1.pValue })
}

