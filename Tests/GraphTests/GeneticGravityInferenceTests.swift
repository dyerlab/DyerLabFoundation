import Testing
import Foundation
import Matrix
@testable import Graph

// MARK: - Fixture decoding

private struct FEdge: Decodable { let from: String; let to: String; let weight: Double }
private struct FGraph: Decodable { let nodes: [String]; let edges: [FEdge] }

private struct FMSR: Decodable {
    let z: [Double]; let W: [[Double]]; let nrepet: Int; let seed: Int
    let replicates: [[Double]]
}
private struct FSourceSink: Decodable {
    let graph: String; let x: [String: Double]; let seed: Int; let nperm: Int
    let null: String; let interior: Bool
    let statistic: Double; let p_value: Double; let nodes: Int; let degree_share: Double
    let r_null: [Double]
    let adjacency: [[Double]]?
}
private struct FCGD: Decodable { let statistic: Double; let p_value: Double; let pairs: Int; let R2: Double; let slope: Double }
private struct FPGDFit: Decodable {
    let delta_R2: Double; let pairs: Int; let R2_cGD: Double; let adj_R2_pGD: Double
    let forward_slope: Double; let reverse_slope: Double; let slope_ratio: Double
}
private struct FIBGD: Decodable {
    let graph: String; let x: [String: Double]; let seed: Int; let nperm: Int
    let distance: [[Double]]; let forward: [[Double]]
    let cgd: FCGD; let pgd: FPGDFit; let pgd_distance_delta_R2: Double
}
private struct FTests: Decodable {
    let msr: [String: FMSR]
    let source_sink: [String: FSourceSink]
    let ibgd: [String: FIBGD]
}

private func fixtureURL(_ name: String) -> URL {
    URL(fileURLWithPath: #filePath).deletingLastPathComponent().appendingPathComponent("Fixtures/\(name)")
}

private func loadTests() throws -> FTests {
    try JSONDecoder().decode(FTests.self, from: Data(contentsOf: fixtureURL("gravity_tests_fixtures.json")))
}

private func loadGraph(_ name: String) throws -> Graph {
    let all = try JSONDecoder().decode([String: FGraph].self,
                                       from: Data(contentsOf: fixtureURL("gravity_fixtures.json")))
    let fixture = try #require(all[name])
    let nodes = fixture.nodes.map { Node(name: $0, size: 1.0) }
    let byName = Dictionary(uniqueKeysWithValues: nodes.map { ($0.name, $0) })
    let edges = fixture.edges.map { Edge(fromNode: byName[$0.from]!, toNode: byName[$0.to]!, weight: $0.weight) }
    return Graph(nodes: nodes, edges: edges)
}

private func matrix(_ rows: [[Double]]) -> Matrix {
    Matrix(rows.count, rows.first?.count ?? 0, rows.flatMap { $0 })
}

// MARK: - msr_null

@Test(arguments: ["path", "chain"])
func moranSpectralRandomizationMatchesR(_ name: String) throws {
    let fixture = try #require(loadTests().msr[name])
    let result = try #require(MoranSpectralRandomization(fixture.z, weights: matrix(fixture.W),
                                                         replicates: fixture.nrepet, seed: fixture.seed))
    #expect(result.rows == fixture.z.count && result.cols == fixture.nrepet)
    for i in 0..<result.rows {
        for k in 0..<result.cols {
            #expect(abs(result[i, k] - fixture.replicates[i][k]) < 1e-9,
                    "\(name) [\(i),\(k)]: \(result[i, k]) vs \(fixture.replicates[i][k])")
        }
    }
}

@Test func moranSpectralRandomizationPreservesMeanAndVariance() throws {
    let fixture = try #require(loadTests().msr["path"])
    let result = try #require(MoranSpectralRandomization(fixture.z, weights: matrix(fixture.W),
                                                         replicates: 50, seed: 3))
    func meanVar(_ v: [Double]) -> (Double, Double) {
        let m = v.reduce(0, +) / Double(v.count)
        return (m, v.reduce(0) { $0 + ($1 - m) * ($1 - m) } / Double(v.count - 1))
    }
    let (zMean, zVar) = meanVar(fixture.z)
    for k in 0..<result.cols {
        let (m, v) = meanVar(result.getCol(c: k))
        #expect(abs(m - zMean) < 1e-10 && abs(v - zVar) < 1e-10)
    }
    // Too few nodes, a non-square W, or a W without a null eigenvalue → nil.
    #expect(MoranSpectralRandomization([1, 2], weights: Matrix(2, 2, 1.0), replicates: 1, seed: 1) == nil)
    #expect(MoranSpectralRandomization([1, 2, 3], weights: Matrix(3, 2, 1.0), replicates: 1, seed: 1) == nil)
}

@Test func symmetricEigendecompositionIsDescendingAndReconstructs() throws {
    let A = matrix([[4, 1, 0.5], [1, 3, 0.2], [0.5, 0.2, 1]])
    let eigen = try #require(SymmetricEigendecomposition(A))
    #expect(eigen.values[0] >= eigen.values[1] && eigen.values[1] >= eigen.values[2])
    for k in 0..<3 {
        let v = eigen.vectors.getCol(c: k)
        for i in 0..<3 {
            let Av = (0..<3).reduce(0.0) { $0 + A[i, $1] * v[$1] }
            #expect(abs(Av - eigen.values[k] * v[i]) < 1e-12)
        }
    }
}

@Test func spearmanUsesAverageRanks() {
    #expect(averageRanks([10, 20, 20, 5]) == [2, 3.5, 3.5, 1])
    #expect(abs(spearmanCorrelation([1, 2, 3, 4], [10, 9, 8, 7]) + 1) < 1e-15)
}

// MARK: - source_sink_test

@Test(arguments: ["chain_graph", "chain_permute", "chain_adjacency", "gravity_graph", "gravity_interior"])
func sourceSinkTestMatchesR(_ name: String) throws {
    let fixture = try #require(loadTests().source_sink[name])
    let graph = try loadGraph(fixture.graph)
    let null: SourceSinkNull
    switch fixture.null {
    case "permute": null = .permute
    case "adjacency": null = .adjacency(matrix(try #require(fixture.adjacency)))
    default: null = .graph
    }
    let result = try #require(SourceSinkTest(graph: graph, x: fixture.x, permutations: fixture.nperm,
                                             null: null, interior: fixture.interior,
                                             returnNull: true, seed: fixture.seed))
    #expect(abs(result.statistic - fixture.statistic) < 1e-12, "\(name) r: \(result.statistic) vs \(fixture.statistic)")
    #expect(result.nodes == fixture.nodes)
    #expect(abs(result.degreeShare - fixture.degree_share) < 1e-10)
    let nullR = try #require(result.nullDistribution)
    #expect(nullR.count == fixture.r_null.count)
    let mismatches = zip(nullR, fixture.r_null).filter { abs($0 - $1) > 1e-9 }.count
    #expect(mismatches == 0, "\(name): \(mismatches) null draws differ from R")
    #expect(abs(result.pValue - fixture.p_value) < 1e-12, "\(name) p: \(result.pValue) vs \(fixture.p_value)")
}

@Test func sourceSinkTestRejectsTooFewNodesAndMissingX() throws {
    let graph = try loadGraph("chain")
    let x = Dictionary(uniqueKeysWithValues: graph.nodes.enumerated().map { ($1.name, Double($0 + 1)) })
    #expect(SourceSinkTest(graph: graph, x: ["P1": 1], permutations: 9, seed: 1) == nil)
    // Interior trimming with a huge margin leaves < 4 nodes.
    #expect(SourceSinkTest(graph: graph, x: x, permutations: 9, interior: true, edgeMargin: 4, seed: 1) == nil)
}

