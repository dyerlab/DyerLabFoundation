import Testing
import Foundation
import Matrix
import Graph
@testable import PopulationGenetics

private struct FixturePermRow: Decodable {
    let from: String; let to: String
    let delta: Double; let statistic: Double; let p_value: Double
}
private struct FixtureCIRow: Decodable {
    let from: String; let to: String
    let delta: Double; let boot_mean: Double?
    let conf_low: Double?; let conf_high: Double?
    let edge_support: Double
}
private struct FixtureStabilityRow: Decodable {
    let from: String; let to: String
    let weight: Double; let probability: Double
}
private struct FixturePermutation: Decodable { let seed: Int; let rows: [FixturePermRow] }
private struct FixtureCI: Decodable { let seed: Int; let conf: Double; let nboot_failed: Int; let rows: [FixtureCIRow] }
private struct FixturePermutePopgraph: Decodable { let seed: Int; let rows: [FixtureStabilityRow] }
private struct FixtureDataset: Decodable {
    let nperm: Int
    let nboot: Int
    let permutation: FixturePermutation
    let ci: FixtureCI
    let permute_popgraph: FixturePermutePopgraph
}

private let datasetNames = ["cornus", "arapat"]

struct AsymmetryPermutationTests {

    private func fixtureURL(_ name: String) -> URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .appendingPathComponent("Fixtures")
            .appendingPathComponent(name)
    }

    private func loadFixtures() throws -> [String: FixtureDataset] {
        let data = try Data(contentsOf: fixtureURL("asymmetry_permutation_fixtures.json"))
        return try JSONDecoder().decode([String: FixtureDataset].self, from: data)
    }

    /// Rebuilds `(graph, data, groups)` for a real dataset exactly as
    /// `PopulationGraphTests.loadRGraph` does, so the observed graph here is
    /// bit-identical to the one the R fixture was built from.
    private func loadDataset(_ name: String) throws -> (graph: Graph, data: Matrix, groups: [String]) {
        let csv = try String(contentsOf: fixtureURL("\(name)_genotypes.csv"), encoding: .utf8)
        let layout = PopulationImportLayout(strataColumns: ["Population"], nameColumn: "ID")
        let imported = try importPopulationTable(csv: csv, layout: layout)
        let matrix = imported.matrix

        let groups = matrix.individuals.map { individual in
            imported.strata[individual.id]?.first(where: { $0.level == "Population" })?.name ?? ""
        }
        let mv = matrix.multivariateMatrix()
        let graph = try #require(PopulationGraph(x: mv, groups: groups), "\(name): PopulationGraph returned nil")
        return (graph, mv, groups)
    }

    // MARK: - asymmetry_permutation

    @Test(arguments: datasetNames)
    func asymmetryPermutationMatchesRExactly(_ name: String) throws {
        let fixture = try #require(loadFixtures()[name])
        let (graph, data, groups) = try loadDataset(name)

        let result = try #require(AsymmetryPermutationTest(graph: graph, data: data, groups: groups,
                                                            permutations: fixture.nperm,
                                                            seed: fixture.permutation.seed))
        #expect(result.count == fixture.permutation.rows.count, "\(name): edge count")

        var expectedByPair: [String: FixturePermRow] = [:]
        for row in fixture.permutation.rows { expectedByPair[pairKey(row.from, row.to)] = row }

        for row in result {
            let exp = try #require(expectedByPair[pairKey(row.from, row.to)],
                                   "\(name): edge \(row.from)-\(row.to) missing from R fixture")
            let orient = exp.from == row.from ? 1.0 : -1.0
            #expect(abs(row.delta - orient * exp.delta) < 1e-9, "\(name) \(row.from)-\(row.to) delta")
            // statistic = delta - mean(null): centred on the per-edge null mean.
            #expect(abs(row.statistic - orient * exp.statistic) < 1e-9,
                    "\(name) \(row.from)-\(row.to) statistic: \(row.statistic) vs \(orient * exp.statistic)")
            // Add-one p-value is an exact k/(B+1) rational — must match to the
            // ULP if the RNG stream (and thus every permutation draw) is identical.
            #expect(abs(row.pValue - exp.p_value) < 1e-12,
                    "\(name) \(row.from)-\(row.to) p: \(row.pValue) vs \(exp.p_value)")
        }
    }

    @Test func asymmetryPermutationRejectsGroupsMissingANode() throws {
        let (graph, data, groups) = try loadDataset("cornus")
        let missing = try #require(graph.nodes.first?.name)
        let relabelled = groups.map { $0 == missing ? "elsewhere" : $0 }
        #expect(AsymmetryPermutationTest(graph: graph, data: data, groups: relabelled,
                                         permutations: 5, seed: 1) == nil)
    }

    // MARK: - asymmetry_ci

    @Test(arguments: datasetNames)
    func asymmetryCIMatchesRExactly(_ name: String) throws {
        let fixture = try #require(loadFixtures()[name])
        let (graph, data, groups) = try loadDataset(name)

        let result = try #require(AsymmetryCI(graph: graph, data: data, groups: groups,
                                              resamples: fixture.nperm,
                                              confidence: fixture.ci.conf,
                                              pendants: .keep,
                                              seed: fixture.ci.seed))
        #expect(result.rows.count == fixture.ci.rows.count, "\(name): edge count")
        #expect(result.failedResamples == fixture.ci.nboot_failed, "\(name): failed resamples")
        #expect(result.pendantEdgeCount == nil)

        var expectedByPair: [String: FixtureCIRow] = [:]
        for row in fixture.ci.rows { expectedByPair[pairKey(row.from, row.to)] = row }

        func close(_ actual: Double, _ expected: Double?) -> Bool {
            guard let expected else { return actual.isNaN }
            return abs(actual - expected) < 1e-9
        }

        for row in result.rows {
            let exp = try #require(expectedByPair[pairKey(row.from, row.to)],
                                   "\(name): edge \(row.from)-\(row.to) missing from R fixture")
            let label = "\(name) \(row.from)-\(row.to)"
            let flipped = exp.from != row.from
            let sign = flipped ? -1.0 : 1.0
            #expect(abs(row.delta - sign * exp.delta) < 1e-9, "\(label) delta")
            #expect(close(row.bootMean, exp.boot_mean.map { sign * $0 }), "\(label) boot_mean")
            // A sign-flipped orientation also swaps the interval bounds.
            let (expLow, expHigh) = flipped
                ? (exp.conf_high.map { -$0 }, exp.conf_low.map { -$0 })
                : (exp.conf_low, exp.conf_high)
            #expect(close(row.confLow, expLow), "\(label) conf.low: \(row.confLow) vs \(String(describing: expLow))")
            #expect(close(row.confHigh, expHigh), "\(label) conf.high")
            // edge_support is an exact k/B rational.
            #expect(abs(row.edgeSupport - exp.edge_support) < 1e-12, "\(label) edge_support")
        }
    }

    @Test func asymmetryCIRejectsInvalidConfidence() throws {
        let (graph, data, groups) = try loadDataset("cornus")
        #expect(AsymmetryCI(graph: graph, data: data, groups: groups, resamples: 2, confidence: 1, seed: 1) == nil)
        #expect(AsymmetryCI(graph: graph, data: data, groups: groups, resamples: 2, confidence: 0, seed: 1) == nil)
    }

    // MARK: - permute_popgraph

    @Test(arguments: datasetNames)
    func permutePopgraphMatchesRExactly(_ name: String) throws {
        let fixture = try #require(loadFixtures()[name])
        let (_, data, groups) = try loadDataset(name)

        let result = try #require(PermutePopgraph(data: data, groups: groups,
                                                   bootstraps: fixture.nboot,
                                                   seed: fixture.permute_popgraph.seed))
        #expect(result.count == fixture.permute_popgraph.rows.count, "\(name): edge count")

        var expectedByPair: [String: FixtureStabilityRow] = [:]
        for row in fixture.permute_popgraph.rows { expectedByPair[pairKey(row.from, row.to)] = row }

        for row in result {
            let exp = try #require(expectedByPair[pairKey(row.from, row.to)],
                                   "\(name): edge \(row.from)-\(row.to) missing from R fixture")
            #expect(abs(row.weight - exp.weight) < 1e-9, "\(name) \(row.from)-\(row.to) weight")
            // Bootstrap support is an exact k/B rational — must match to the
            // ULP if the RNG stream (and thus every bootstrap draw) is identical.
            #expect(abs(row.probability - exp.probability) < 1e-12,
                    "\(name) \(row.from)-\(row.to) probability: \(row.probability) vs \(exp.probability)")
        }
    }
}

private func pairKey(_ a: String, _ b: String) -> String {
    a < b ? "\(a)\u{1}\(b)" : "\(b)\u{1}\(a)"
}
