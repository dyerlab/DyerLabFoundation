import Testing
import Foundation
import Matrix
import Graph
@testable import PopulationGenetics

private struct FEdge: Decodable { let from: String; let to: String; let weight: Double }
private struct FSubsampleRow: Decodable {
    let k: Int; let subset: Int; let n_poly_global: Int; let n_poly_pop: Double; let He: Double
    let n_edges: Int?; let mean_abs_delta: Double?; let ok: Int; let loci: [String]
}
private struct FSubsample: Decodable {
    let seed: Int; let k: [Int]; let nsub: Int; let polymorphic: [String]; let rows: [FSubsampleRow]
}
private struct FPGD: Decodable {
    let nodes: [String]
    let popgraph_edges: [FEdge]
    let pgd: [[Double?]]
}

struct PartitionedGeneticDistanceTests {

    private func fixtureURL(_ name: String) -> URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .appendingPathComponent("Fixtures")
            .appendingPathComponent(name)
    }

    private func loadGravityGenotypes() throws -> (genotypes: GenotypeMatrix, groups: [String]) {
        let csv = try String(contentsOf: fixtureURL("gravity_genotypes.csv"), encoding: .utf8)
        let layout = PopulationImportLayout(strataColumns: ["Population"], nameColumn: "ID")
        let imported = try importPopulationTable(csv: csv, layout: layout)
        let groups = imported.matrix.individuals.map { individual in
            imported.strata[individual.id]?.first(where: { $0.level == "Population" })?.name ?? ""
        }
        return (imported.matrix, groups)
    }

    private func loadGravity() throws -> (data: Matrix, groups: [String]) {
        let (genotypes, groups) = try loadGravityGenotypes()
        return (genotypes.multivariateMatrix(), groups)
    }

    @Test func gravityPopulationGraphAndPGDMatchR() throws {
        let fixture = try JSONDecoder().decode(FPGD.self,
                                               from: Data(contentsOf: fixtureURL("gravity_pgd_fixture.json")))
        let (data, groups) = try loadGravity()

        // The Population Graph itself (25 demes, 81 edges in R).
        let graph = try #require(PopulationGraph(x: data, groups: groups))
        let names = Dictionary(uniqueKeysWithValues: graph.nodes.map { ($0.id, $0.name) })
        var weights: [Set<String>: Double] = [:]
        for edge in graph.edges { weights[[names[edge.fromNode]!, names[edge.toNode]!]] = edge.weight }
        #expect(weights.count == fixture.popgraph_edges.count, "edge count \(weights.count) vs R \(fixture.popgraph_edges.count)")
        for edge in fixture.popgraph_edges {
            let actual = try #require(weights[[edge.from, edge.to]], "missing edge \(edge.from)-\(edge.to)")
            #expect(abs(actual - edge.weight) < 1e-8, "\(edge.from)-\(edge.to) weight")
        }

        // The directed pGD matrix, compared by stratum name.
        let D = try #require(PartitionedGeneticDistance(data: data, groups: groups))
        for (i, from) in fixture.nodes.enumerated() {
            let r = try #require(D.rowNames.firstIndex(of: from))
            for (j, to) in fixture.nodes.enumerated() {
                let c = try #require(D.colNames.firstIndex(of: to))
                let expected = try #require(fixture.pgd[i][j], "R pGD unexpectedly NA")
                #expect(abs(D[r, c] - expected) < 1e-8, "pGD[\(from),\(to)]: \(D[r, c]) vs \(expected)")
            }
        }
    }

    /// `locus_subsample_null()`: the seeded locus draws match R, and so does
    /// everything computed from each subset — polymorphism, He, and the rebuilt
    /// graph's edge count and mean |Δ|.
    @Test func locusSubsampleNullMatchesR() throws {
        let fixture = try JSONDecoder().decode(FSubsample.self,
                                               from: Data(contentsOf: fixtureURL("gravity_locus_subsample_fixture.json")))
        let (genotypes, groups) = try loadGravityGenotypes()
        let draws = try #require(LocusSubsampleNull(genotypes: genotypes, groups: groups,
                                                    lociPerSubset: fixture.k, subsets: fixture.nsub,
                                                    seed: fixture.seed))
        #expect(draws.count == fixture.rows.count)
        for (draw, expected) in zip(draws, fixture.rows) {
            let label = "k=\(expected.k) #\(expected.subset)"
            #expect(draw.k == expected.k && draw.subset == expected.subset, "\(label)")
            #expect(draw.loci == expected.loci, "\(label) loci: \(draw.loci) vs \(expected.loci)")
            #expect(draw.polymorphicGlobal == expected.n_poly_global, "\(label) n_poly_global")
            #expect(abs(draw.polymorphicPerPopulation - expected.n_poly_pop) < 1e-12, "\(label) n_poly_pop")
            #expect(abs(draw.expectedHeterozygosity - expected.He) < 1e-12,
                    "\(label) He: \(draw.expectedHeterozygosity) vs \(expected.He)")
            #expect(draw.succeeded == (expected.ok == 1), "\(label) ok")
            #expect(draw.edgeCount == expected.n_edges, "\(label) n_edges: \(String(describing: draw.edgeCount)) vs \(String(describing: expected.n_edges))")
            if let expectedDelta = expected.mean_abs_delta, let delta = draw.meanAbsDelta {
                #expect(abs(delta - expectedDelta) < 1e-8, "\(label) mean|Δ|: \(delta) vs \(expectedDelta)")
            }
        }
    }
}
